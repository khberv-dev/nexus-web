/** Договор считается заключенным для отправки брифа и рабочих статусов заказа (клиент или админ). */
export function isFrameworkContractEffectiveSigned(status: string | null | undefined): boolean {
  return status === "SIGNED_BY_CLIENT" || status === "SIGNED_BY_ADMIN"
}

