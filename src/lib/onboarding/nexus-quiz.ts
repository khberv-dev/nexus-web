function normAnswer(answers: Record<string, number | string>): Record<number, number> {
    const out: Record<number, number> = {}
    for (const [k, v] of Object.entries(answers)) {
        const id = Number(k)
        const num = typeof v === "string" ? Number(v) : v
        if (!Number.isFinite(id) || !Number.isFinite(num)) continue
        out[id] = num
    }
    return out
}

export type NexusQuizGrade = {
    correctCount: number
    total: number
    percent: number
    passed: boolean
    passPercent: number
    sectionScores: Record<string, { correct: number; total: number }>
}

export function gradeNexusQuiz(answers: Record<string, number>): NexusQuizGrade {
    const norm = normAnswer(answers)
    const sectionScores: Record<string, { correct: number; total: number }> = {}
    let correctCount = 0
    const total = NEXUS_QUIZ_QUESTIONS.length

    for (const q of NEXUS_QUIZ_QUESTIONS) {
        if (!sectionScores[q.section]) sectionScores[q.section] = {correct: 0, total: 0}
        sectionScores[q.section].total++
        const a = norm[q.id]
        if (a === q.correct) {
            correctCount++
            sectionScores[q.section].correct++
        }
    }

    const percent = total === 0 ? 0 : Math.round((correctCount / total) * 100)
    const passed = percent >= NEXUS_QUIZ_PASS_PERCENT
    return {correctCount, total, percent, passed, passPercent: NEXUS_QUIZ_PASS_PERCENT, sectionScores}
}

/** Проверка, что пришли ответы на все вопросы, индексы вариантов -1 (тайм-аут) или 0..3. */
export function validateQuizAnswersPayload(answers: unknown): answers is Record<string, number> {
    if (!answers || typeof answers !== "object" || Array.isArray(answers)) return false
    const norm = normAnswer(answers as Record<string, number>)
    if (Object.keys(norm).length !== NEXUS_QUIZ_QUESTIONS.length) return false
    for (const q of NEXUS_QUIZ_QUESTIONS) {
        const v = norm[q.id]
        if (typeof v !== "number" || !Number.isInteger(v) || v < -1 || v > 3) return false
    }
    return true
}

export type StoredTestMeta = {
    correctCount: number
    percent: number
    passed: boolean
    passPercent: number
}

function answersFromAttempts(attempts: Array<Record<string, unknown>>): Record<string, number> | null {
    for (let i = attempts.length - 1; i >= 0; i--) {
        const raw = attempts[i]?.answers
        if (raw && typeof raw === "object" && !Array.isArray(raw) && Object.keys(raw as object).length > 0) {
            return raw as Record<string, number>
        }
    }
    return null
}

/** Разбор поля comment шага TEST (новый JSON или legacy только ответы). */
export function parseStoredTestComment(comment: string | null): {
    answers: Record<string, number>
    meta: StoredTestMeta | null
    currentLevel?: string
} {
    if (!comment) return {answers: {}, meta: null}
    try {
        const parsed = JSON.parse(comment) as Record<string, unknown>
        if (
            parsed &&
            typeof parsed === "object" &&
            (parsed.version === 4 || parsed.version === 5) &&
            parsed.answers &&
            typeof parsed.answers === "object" &&
            !Array.isArray(parsed.answers)
        ) {
            const attempts = Array.isArray(parsed.attempts) ? (parsed.attempts as Array<Record<string, unknown>>) : []
            const last = attempts[attempts.length - 1]
            const liveAnswers = parsed.answers as Record<string, number>
            const archivedAnswers = answersFromAttempts(attempts)
            const answers =
                Object.keys(liveAnswers).length > 0 ? liveAnswers : (archivedAnswers ?? liveAnswers)
            return {
                answers,
                currentLevel: typeof parsed.currentLevel === "string" ? parsed.currentLevel : undefined,
                meta: last
                    ? {
                        correctCount: Number(last.correctCount) || 0,
                        percent: Number(last.percent) || 0,
                        passed: Boolean(last.passed),
                        passPercent: Number(parsed.passPercent) || 80,
                    }
                    : null,
            }
        }
        if (
            parsed &&
            typeof parsed === "object" &&
            parsed.version === 3 &&
            parsed.answers &&
            typeof parsed.answers === "object" &&
            !Array.isArray(parsed.answers)
        ) {
            return {answers: parsed.answers as Record<string, number>, meta: null}
        }
        if (
            parsed &&
            typeof parsed === "object" &&
            parsed.version === 2 &&
            parsed.answers &&
            typeof parsed.answers === "object" &&
            !Array.isArray(parsed.answers)
        ) {
            return {
                answers: parsed.answers as Record<string, number>,
                meta: {
                    correctCount: Number(parsed.correctCount),
                    percent: Number(parsed.percent),
                    passed: Boolean(parsed.passed),
                    passPercent: Number(parsed.passPercent),
                },
            }
        }
        const keys = Object.keys(parsed)
        if (keys.length && keys.every((k) => /^\d+$/.test(k))) {
            return {answers: parsed as unknown as Record<string, number>, meta: null}
        }
    } catch {
        /* ignore */
    }
    return {answers: {}, meta: null}
}

/** Прогресс квиза по одному ответу (этап IN_PROGRESS, version 3). */
export type QuizProgressStored = {
    version: 3
    phase: "in_progress"
    answers: Record<string, number>
    answeredCount: number
    liveCorrect: number
    total: number
    lastQuestionId: number
}

export function parseQuizProgress(comment: string | null): (QuizProgressStored & { currentLevel?: string }) | null {
    if (!comment) return null
    try {
        const p = JSON.parse(comment) as Record<string, unknown>
        if (
            p.version === 3 &&
            p.phase === "in_progress" &&
            p.answers &&
            typeof p.answers === "object" &&
            !Array.isArray(p.answers)
        ) {
            const answers = p.answers as Record<string, number>
            return {
                version: 3,
                phase: "in_progress",
                answers,
                answeredCount: Number(p.answeredCount) || Object.keys(answers).length,
                liveCorrect: Number(p.liveCorrect) || 0,
                total: Number(p.total) || NEXUS_QUIZ_QUESTIONS.length,
                lastQuestionId: Number(p.lastQuestionId) || 0,
                currentLevel: typeof p.currentLevel === "string" ? p.currentLevel : undefined,
            }
        }
        if (
            (p.version === 4 || p.version === 5) &&
            p.phase === "level_in_progress" &&
            p.answers &&
            typeof p.answers === "object" &&
            !Array.isArray(p.answers)
        ) {
            const answers = p.answers as Record<string, number>
            return {
                version: 3,
                phase: "in_progress",
                answers,
                answeredCount: Number(p.answeredCount) || Object.keys(answers).length,
                liveCorrect: Number(p.liveCorrect) || 0,
                total: Number(p.total) || NEXUS_QUIZ_QUESTIONS.length,
                lastQuestionId: Number(p.lastQuestionId) || 0,
                currentLevel: typeof p.currentLevel === "string" ? p.currentLevel : undefined,
            }
        }
    } catch {
        /* ignore */
    }
    return null
}

/** Состояние сегмента мини-шкалы (админка / экран теста): цвет + подсказка с выбранным вариантом. */
export type QuizMicroTickState = "pending" | "correct" | "wrong"

export function getQuizMicroTick(
    questionIndex: number,
    answers: Record<string, number> | Record<number, number>,
    questions?: readonly { id: number; options: readonly string[]; correct: number }[]
): { state: QuizMicroTickState; tooltip: string } {
    const q = (questions ?? NEXUS_QUIZ_QUESTIONS)[questionIndex]
    if (!q) return {state: "pending", tooltip: ""}
    const norm = normAnswer(answers as Record<string, number>)
    const selected = norm[q.id]
    if (selected === undefined) {
        return {state: "pending", tooltip: `Вопрос ${q.id}: еще не отвечен`}
    }
    if (selected === -1) {
        return {state: "wrong", tooltip: `Вопрос ${q.id}: время вышло`}
    }
    const optText = q.options[selected] ?? "—"
    const ok = selected === q.correct
    return {
        state: ok ? "correct" : "wrong",
        tooltip: ok
            ? `Вопрос ${q.id}: выбрано «${optText}» (верно)`
            : `Вопрос ${q.id}: выбрано «${optText}» (неверно)`,
    }
}

/** Число верных ответов среди уже выбранных вопросов. */
export function countCorrectSoFar(answers: Record<string, number>): number {
    const norm = normAnswer(answers)
    let n = 0
    for (const q of NEXUS_QUIZ_QUESTIONS) {
        if (norm[q.id] === undefined) continue
        if (norm[q.id] === q.correct) n++
    }
    return n
}
