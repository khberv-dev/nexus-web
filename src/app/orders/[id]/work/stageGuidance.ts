import type {StageStatus, StageType} from "../types"

/** Зачем этот этап в цепочке (бриф → реализация). */
export function stagePurpose(type: StageType): string {
    const copy: Record<StageType, string> = {
        CONCEPT:
            "Зафиксировать направление проекта: настроение, стиль, ключевые образы и первые визуальные намётки. От этого зависят все следующие этапы.",
        PLANNING:
            "Согласовать планировку и зонирование: расстановку мебели, проходы, функциональные узлы. Без принятого плана нельзя уверенно двигаться к детальной картинке и чертежам.",
        VISUALIZATION:
            "Увидеть интерьер объёмно: колористика, материалы, свет, мебель в пространстве. Цель — утвердить внешний вид до дорогой рабочей документации и закупок.",
        DOCUMENTATION:
            "Получить комплект рабочих материалов для стройки и подрядчиков (планы, развертки, узлы по договорённостям). Это основа для реализации «как задумано».",
        SPECIFICATION:
            "Свести финиши, освещение, оборудование и позиции для закупки в понятный список. Нужен для бюджета, заказов и чтобы на объекте не осталось белых пятен.",
    }
    return copy[type]
}

/**
 * Что означает текущий статус в state machine и что делать заказчику.
 */
export function stageStatusGuidance(type: StageType, status: StageStatus): string {
    const name = type === "CONCEPT" ? "концепцию" : "материалы этапа"

    switch (status) {
        case "AWAITING_PAYMENT":
            return "Этап открыт, но не оплачен аванс/этапная оплата. Завершите оплату в карточке этапа справа — после этого дизайнер сможет вести работу по регламенту."

        case "BLOCKED":
            return "Этап станет доступен, когда предыдущий этап будет принят. Загрузки и согласование по нему сейчас недоступны."

        case "PENDING":
            if (type === "CONCEPT") {
                return "Начать этап должен специалист: он готовит и загружает первую подборку по концепции. Заказчику нужно дождаться появления материалов справа."
            }
            return "Начать этап должен специалист: он загрузит первые материалы. После этого этап перейдёт к проверке и согласованию."

        case "UPLOADED":
            return `Дизайнер загрузил черновой комплект по ${name}. Сейчас идёт внутренняя проверка модератора; как только она пройдена, этап поступит вам на ознакомление и решение.`

        case "MOD_REVIEW":
            return "Комплект на проверке у модератора платформы (соответствие брифу и правилам сдачи). Ожидайте результата — после этого материалы придут к вам либо уйдут на доработку дизайнеру."

        case "MOD_REVISION":
            return "Модератор вернул этап на доработку дизайнеру. Дождитесь обновлённой версии файлов; после повторной проверки этап снова попадёт к вам."

        case "CLIENT_REVIEW":
            return "Ваша очередь: откройте материалы справа, сравните с брифом и целями этапа. Можно принять этап или запросить правки — чем конкретнее список замечаний, тем быстрее результат."

        case "CLIENT_REVISION":
            return "Вы запросили правки; дизайнер готовит новую версию. После загрузки снова пройдёт модерация и этап вернётся к вам на повторное решение."

        case "EXTRA_PAYMENT":
            return "Требуется доплата (например, сверх включённого числа раундов правок или по условиям этапа). Оплатите блок доплаты в карточке — затем работа по правкам продолжится."

        case "APPROVED":
            return "Этап принят и зафиксирован в цепочке. Следите за сеткой этапов: когда откроется следующий, переходите к нему. Если по регламенту нужен акт по этому этапу — подпишите его в карточке ниже."

        default:
            return "Статус обновляется автоматически по ходу работы. Смотрите материалы и действия в карточке этапа справа."
    }
}
